// Upserts original, SEO-safe product descriptions into product_content and
// writes a matching SQL seed file (018) for the repo record.
// Run: node --env-file-if-exists=/vercel/share/.env.project scripts/apply-descriptions.mjs
import { readFile, writeFile } from "node:fs/promises"

const url = process.env.NEXT_PUBLIC_SUPABASE_URL || process.env.SUPABASE_URL
const key =
  process.env.SUPABASE_SERVICE_ROLE_KEY ||
  process.env.SUPABASE_SERVICE_ROLE ||
  process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY

if (!url || !key) {
  console.error("Missing Supabase env vars")
  process.exit(1)
}

const data = JSON.parse(await readFile(new URL("./product-descriptions.json", import.meta.url)))
const rows = Object.entries(data).map(([category_slug, description]) => ({
  category_slug,
  description,
  updated_at: new Date().toISOString(),
}))

// 1. Upsert to Supabase via REST (merge duplicates on the category_slug PK)
const res = await fetch(`${url}/rest/v1/product_content?on_conflict=category_slug`, {
  method: "POST",
  headers: {
    apikey: key,
    Authorization: `Bearer ${key}`,
    "Content-Type": "application/json",
    Prefer: "resolution=merge-duplicates,return=minimal",
  },
  body: JSON.stringify(rows),
})

if (!res.ok) {
  console.error("Upsert failed:", res.status, await res.text())
  process.exit(1)
}
console.log(`Upserted ${rows.length} descriptions to product_content.`)

// 2. Emit a SQL seed file matching the existing 015-017 convention
const esc = (s) => s.replace(/'/g, "''")
const values = Object.entries(data)
  .map(([slug, desc]) => `('${slug}',\n '${esc(desc)}')`)
  .join(",\n\n")
const sql = `-- Original, SEO-safe product descriptions authored in Web2Print USA's own voice.
-- Rewrites the earlier verbatim vendor copy (scripts 016/017) and fills every
-- remaining product-type slug. Generated by scripts/apply-descriptions.mjs.
-- Run in Supabase SQL Editor (or via the apply script).

INSERT INTO product_content (category_slug, description)
VALUES

${values}

ON CONFLICT (category_slug) DO UPDATE
  SET description = EXCLUDED.description,
      updated_at  = NOW();
`
await writeFile(new URL("./018_product_descriptions_reworded.sql", import.meta.url), sql)
console.log("Wrote scripts/018_product_descriptions_reworded.sql")
